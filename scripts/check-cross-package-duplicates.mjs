/**
 * check-cross-package-duplicates.mjs — a down-only ratchet on which file
 * pairs share duplicated logic or styles, in the same package or a different
 * one. (Named for its original cross-package-only scope; kept for a smaller
 * diff. `KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS` below can hold either kind.)
 * Same shape as packages/maximal-core/scripts/check-dupes.ts's duplicate-pair
 * ratchet: hold a SET of known pairs, fail only when a NEW one appears or a
 * known one silently disappears unrecorded, and let `--update` re-record the
 * set after a deliberate fix.
 *
 *   node scripts/check-cross-package-duplicates.mjs             # gate
 *   node scripts/check-cross-package-duplicates.mjs --list      # inventory
 *   node scripts/check-cross-package-duplicates.mjs --update    # re-record
 *   node scripts/check-cross-package-duplicates.mjs <paths...>  # ripgrep-style scope
 *
 * Wired into the build (see package.json `check`): unlike mutation testing,
 * this is cheap enough to run every time, and a workspace-wide first pass is
 * expected to surface some intra-package boilerplate along with the real
 * finds — seed the baseline with what it finds and prune from there.
 *
 * check-dupes.ts's jscpd gate is per package, so nothing there sees
 * duplication BETWEEN packages. This tool adds that, and — because it uses a
 * different engine for JS/TS — also catches renamed-identifier duplication
 * WITHIN a package that check-dupes.ts's literal token match misses:
 *
 * - `jsinspect-plus` for JS/TS/TSX: it compares AST *structure*
 *   (`--no-identifiers --no-literals`), so a renamed, re-literaled copy still
 *   matches — unlike jscpd's token match. It parses with Babel, so it
 *   cannot see CSS at all (confirmed empirically: pointed at a CSS-only tree
 *   it reports zero files found, not zero clones).
 * - Core's pinned `jscpd` (`--format css`) for `.css`: the same token matcher
 *   check-dupes.ts uses for TS, format-restricted to CSS. This is still only
 *   literal copy-paste, not renamed-value or restructured duplication —
 *   jsinspect's structural comparison doesn't have a CSS-capable engine to
 *   run it with here.
 *
 * Neither finds a genuine reimplementation — different code (or markup),
 * same idea, shares no tokens and no structure either.
 *
 * Thresholds were both chosen by measuring across every package `src` tree:
 * - JS/TS: 40 and 60 AST nodes still matched a single generic
 *   entrypoint/re-export shape shared by unrelated files across five
 *   packages, fanning out into dozens of pairs that are the shape of a small
 *   `index.ts`, not a defect. At 80 that shape drops out and the two
 *   remaining cross-package matches are each a plausible real pair.
 * - CSS: 30 min-tokens found 4 cross-package clones, each a few lines of
 *   boilerplate shared between three small, independently developed widget
 *   packages' `styles.css` — exactly the shape this tool exists to catch.
 * Re-measure before changing either.
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { readArchitecturePolicy } from "./architecture-graph.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const JS_THRESHOLD = 80;
const CSS_MIN_TOKENS = 30;
const IGNORE_PATTERN = "\\.(test|stories)\\.";
const JSINSPECT_BIN = path.join(
  ROOT,
  "node_modules/jsinspect-plus/bin/jsinspect",
);
const JSCPD_BIN = path.join(
  ROOT,
  "packages/maximal-core/node_modules/jscpd/run-jscpd.js",
);
const REPORT_DIR = path.join(ROOT, "reports/cross-package-duplicates");

// --- BEGIN KNOWN CROSS-PACKAGE DUPLICATE PAIRS — generated by `node scripts/check-cross-package-duplicates.mjs --update` ---
const KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS = [
  "packages/maximal-context-window/src/styles.css <-> packages/maximal-data-visualization/src/styles.css",
  "packages/maximal-context-window/src/styles.css <-> packages/maximal-observability/src/styles.css",
  "packages/maximal-core/src/lib/host-config/json-resource-set.ts <-> packages/maximal-core/src/lib/host-config/json-target.ts",
  "packages/maximal-electron/src/renderer/index.ts <-> packages/maximal/client/src/renderer/settings/capabilities.ts",
  "packages/maximal-electron/src/renderer/lib/content-lorem.ts <-> packages/maximal-electron/src/renderer/lib/content.ts",
  "packages/maximal-electron/src/renderer/styles/controls.css <-> packages/maximal-electron/src/renderer/styles/shell.css",
  "packages/maximal-electron/src/renderer/styles/shell-package-rules.css <-> packages/maximal-electron/src/renderer/styles/shell.css",
  "packages/maximal-observability/src/Overview.tsx <-> packages/maximal-observability/src/TrafficExplorer.tsx",
];
// --- END KNOWN CROSS-PACKAGE DUPLICATE PAIRS ---

export function packageRoots(root = ROOT) {
  const policy = readArchitecturePolicy(root);
  return Object.entries(policy.packages)
    .map(([name, options]) => ({
      name,
      root: options.root.replace(/\/$/, ""),
    }))
    .sort((left, right) => right.root.length - left.root.length);
}

export function packageForPath(packages, relativePath) {
  const clean = relativePath.replace(/^\.\//, "");
  for (const pkg of packages) {
    if (clean === pkg.root || clean.startsWith(`${pkg.root}/`)) return pkg.name;
  }
  return undefined;
}

/** Ripgrep-style: files/dirs given on the command line, resolved to repo-relative POSIX paths. */
export function resolveScopePaths(rawPaths, cwd = process.cwd(), root = ROOT) {
  return rawPaths.map((raw) => {
    const relative = path.relative(root, path.resolve(cwd, raw));
    if (relative.startsWith("..") || path.isAbsolute(relative)) {
      throw new Error(`Path is outside the repository: ${raw}`);
    }
    return relative.split(path.sep).join("/");
  });
}

export function withinScope(scope, relativePath) {
  if (scope.length === 0) return true;
  return scope.some(
    (entry) => relativePath === entry || relativePath.startsWith(`${entry}/`),
  );
}

function pairWithinScope(scope, id) {
  const [left, right] = id.split(" <-> ");
  return withinScope(scope, left) && withinScope(scope, right);
}

function defaultTargets(packages, root) {
  return packages
    .map((pkg) => path.join(pkg.root, "src"))
    .filter((src) => fs.statSync(path.join(root, src), { throwIfNoEntry: false })?.isDirectory());
}

function runJsinspect(targets, root) {
  // jsinspect-plus exits non-zero when it finds matches; the report is what matters, not the exit code.
  const result = spawnSync(
    process.execPath,
    [
      JSINSPECT_BIN,
      "-r", "json",
      "-t", String(JS_THRESHOLD),
      "-I",
      "-L",
      "--ignore", IGNORE_PATTERN,
      ...targets,
    ],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.error) {
    throw new Error(`jsinspect-plus could not start: ${result.error.message}`);
  }
  if (!result.stdout?.trim()) {
    if (result.stderr?.trim()) throw new Error(result.stderr.trim());
    return [];
  }
  return JSON.parse(result.stdout);
}

/** Core's pinned jscpd, format-restricted to CSS — jsinspect-plus's Babel parser cannot read it. */
function runJscpd(targets, root) {
  const output = fs.mkdtempSync(path.join(os.tmpdir(), "jscpd-css-"));
  try {
    const result = spawnSync(
      process.execPath,
      [
        JSCPD_BIN,
        ...targets,
        "--min-tokens", String(CSS_MIN_TOKENS),
        "--format", "css",
        "--absolute",
        "--no-colors",
        "--reporters", "json",
        "--output", output,
      ],
      { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
    );
    if (result.error) throw new Error(`jscpd could not start: ${result.error.message}`);
    const reportPath = path.join(output, "jscpd-report.json");
    if (!fs.statSync(reportPath, { throwIfNoEntry: false })?.isFile()) {
      throw new Error(
        `jscpd did not produce a report${result.stderr?.trim() ? `: ${result.stderr.trim()}` : ""}`,
      );
    }
    const report = JSON.parse(fs.readFileSync(reportPath, "utf8"));
    if (!Array.isArray(report.duplicates)) {
      throw new TypeError("jscpd report had no `duplicates` array");
    }
    return report.duplicates;
  } finally {
    fs.rmSync(output, { recursive: true, force: true });
  }
}

/** Records every unordered pair among a set of same-match instances, skipping only a file matched against itself (visible to the reviewer already, not this tool's job). */
function addDuplicatePairs(pairs, packages, instances) {
  for (let i = 0; i < instances.length; i += 1) {
    for (let j = i + 1; j < instances.length; j += 1) {
      const left = instances[i];
      const right = instances[j];
      if (left.path === right.path) continue;
      if (!packageForPath(packages, left.path) || !packageForPath(packages, right.path)) continue;

      const [first, second] = [left.path, right.path].sort();
      const id = `${first} <-> ${second}`;
      const existing = pairs.get(id) ?? [];
      existing.push([left, right]);
      pairs.set(id, existing);
    }
  }
}

/** Every unordered file pair that jsinspect matched as structurally similar, same or different package. */
export function crossPackagePairs(matches, packages) {
  const pairs = new Map();
  for (const match of matches) {
    const instances = match.instances.map((instance) => ({
      path: instance.path.replace(/^\.\//, ""),
      lines: instance.lines,
    }));
    addDuplicatePairs(pairs, packages, instances);
  }
  return pairs;
}

/** Every unordered file pair that jscpd matched as a CSS token clone, same or different package. */
export function crossPackagePairsFromClones(clones, packages, root = ROOT) {
  const pairs = new Map();
  const relative = (absolute) =>
    path.relative(fs.realpathSync(root), fs.realpathSync(absolute)).split(path.sep).join("/");
  for (const clone of clones) {
    const left = { path: relative(clone.firstFile.name), lines: [clone.firstFile.start, clone.firstFile.end] };
    const right = { path: relative(clone.secondFile.name), lines: [clone.secondFile.start, clone.secondFile.end] };
    if (left.path === right.path) continue;
    addDuplicatePairs(pairs, packages, [left, right]);
  }
  return pairs;
}

/** Combines pair maps from both engines, keeping every matched instance under each shared pair id. */
export function mergePairs(...maps) {
  const merged = new Map();
  for (const map of maps) {
    for (const [id, instances] of map) {
      merged.set(id, [...(merged.get(id) ?? []), ...instances]);
    }
  }
  return merged;
}

export function describeMatch([left, right]) {
  return `${left.path}:${left.lines[0]}-${left.lines[1]} <-> ${right.path}:${right.lines[0]}-${right.lines[1]}`;
}

/** Reads the exact matched lines back off disk, so the report shows real code, not just a location. */
export function readSnippet(root, relativePath, lines) {
  try {
    const content = fs.readFileSync(path.join(root, relativePath), "utf8").split("\n");
    return content.slice(lines[0] - 1, lines[1]);
  } catch {
    return undefined;
  }
}

/**
 * A kdiff-style line alignment (longest-common-subsequence), so the HTML
 * report can show two snippets side by side with only the real differences
 * highlighted — not just "these two locations matched".
 */
export function diffLines(left, right) {
  const n = left.length;
  const m = right.length;
  const table = Array.from({ length: n + 1 }, () => new Array(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i -= 1) {
    for (let j = m - 1; j >= 0; j -= 1) {
      table[i][j] =
        left[i] === right[j] ?
          table[i + 1][j + 1] + 1
        : Math.max(table[i + 1][j], table[i][j + 1]);
    }
  }
  const ops = [];
  let i = 0;
  let j = 0;
  while (i < n && j < m) {
    if (left[i] === right[j]) {
      ops.push({ type: "same", left: left[i], right: right[j] });
      i += 1;
      j += 1;
    } else if (table[i + 1][j] >= table[i][j + 1]) {
      ops.push({ type: "left", left: left[i] });
      i += 1;
    } else {
      ops.push({ type: "right", right: right[j] });
      j += 1;
    }
  }
  while (i < n) {
    ops.push({ type: "left", left: left[i] });
    i += 1;
  }
  while (j < m) {
    ops.push({ type: "right", right: right[j] });
    j += 1;
  }
  return ops;
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function renderDiffTable(ops) {
  const rows = ops.map((op) => {
    if (op.type === "same") {
      return `<tr><td class="same">${escapeHtml(op.left)}</td><td class="same">${escapeHtml(op.right)}</td></tr>`;
    }
    if (op.type === "left") {
      return `<tr><td class="removed">${escapeHtml(op.left)}</td><td class="empty"></td></tr>`;
    }
    return `<tr><td class="empty"></td><td class="added">${escapeHtml(op.right)}</td></tr>`;
  });
  return `<table class="diff"><tbody>${rows.join("")}</tbody></table>`;
}

const REPORT_CSS =
  "body{font:14px/1.5 -apple-system,sans-serif;margin:2rem;color:#1a1a1a}" +
  "h1{font-size:1.3rem}h2{font-size:1rem;margin:0 0 .5rem}" +
  "section{border:1px solid #ddd;border-radius:6px;padding:1rem;margin-bottom:1rem}" +
  "section.new{border-color:#c0392b;background:#fff6f5}" +
  "section.known{border-color:#bbb}" +
  ".locations{display:flex;justify-content:space-between;font-family:monospace;font-size:.8rem;color:#555;margin:.5rem 0 .25rem}" +
  "table.diff{width:100%;border-collapse:collapse;table-layout:fixed;margin-bottom:.75rem}" +
  "table.diff td{width:50%;font-family:monospace;font-size:.8rem;white-space:pre-wrap;word-break:break-all;padding:1px 6px;vertical-align:top}" +
  "td.same{background:#fff}td.removed{background:#ffe4e1}td.added{background:#e3f7e3}td.empty{background:#f4f4f4}";

function renderHtml(entries, root) {
  const sections = entries.map((entry) => {
    const instanceBlocks = entry.instances
      .map(({ left, right }) => {
        const leftLines = readSnippet(root, left.path, left.lines);
        const rightLines = readSnippet(root, right.path, right.lines);
        const table =
          leftLines && rightLines ?
            renderDiffTable(diffLines(leftLines, rightLines))
          : "<p><em>(source unavailable — file moved or scope changed since the scan)</em></p>";
        return (
          `<div class="locations"><span>${escapeHtml(left.path)}:${left.lines[0]}-${left.lines[1]}</span>` +
          `<span>${escapeHtml(right.path)}:${right.lines[0]}-${right.lines[1]}</span></div>${table}`
        );
      })
      .join("");
    return (
      `<section class="${entry.known ? "known" : "new"}">` +
      `<h2>${entry.known ? "GATE" : "NEW"} — ${escapeHtml(entry.id)}</h2>${instanceBlocks}</section>`
    );
  });
  return (
    "<!doctype html><html><head><meta charset=\"utf-8\">" +
    `<title>Cross-package duplicates</title><style>${REPORT_CSS}</style></head><body>` +
    "<h1>Cross-package duplicates</h1>" +
    `<p>${entries.length} pair(s), ${entries.filter((entry) => !entry.known).length} new. Each row pair is a kdiff-style` +
    " alignment of the two matched snippets — white is shared, red is only on the left, green only on the right.</p>" +
    `${sections.join("")}</body></html>`
  );
}

/** Persists the current findings so a run leaves behind more than a console log. */
export function writeReport(pairs, known, reportDir = REPORT_DIR, root = ROOT) {
  fs.mkdirSync(reportDir, { recursive: true });
  const current = [...pairs.keys()].sort();
  const entries = current.map((id) => ({
    id,
    known: known.includes(id),
    instances: (pairs.get(id) ?? []).map(([left, right]) => ({
      left: { path: left.path, lines: left.lines },
      right: { path: right.path, lines: right.lines },
    })),
  }));
  const report = {
    generatedAt: new Date().toISOString(),
    summary: {
      total: current.length,
      known: entries.filter((entry) => entry.known).length,
      new: entries.filter((entry) => !entry.known).length,
    },
    pairs: entries,
  };
  fs.writeFileSync(path.join(reportDir, "report.json"), `${JSON.stringify(report, null, 2)}\n`);

  const lines = [`${current.length} duplicate pair(s), generated ${report.generatedAt}:`, ""];
  for (const entry of entries) {
    lines.push(`${entry.known ? "GATE" : "new "}  ${entry.id}`);
    for (const instance of entry.instances) {
      lines.push(`        ${instance.left.path}:${instance.left.lines[0]}-${instance.left.lines[1]} <-> ${instance.right.path}:${instance.right.lines[0]}-${instance.right.lines[1]}`);
    }
  }
  fs.writeFileSync(path.join(reportDir, "report.txt"), `${lines.join("\n")}\n`);
  fs.writeFileSync(path.join(reportDir, "report.html"), renderHtml(entries, root));
  return {
    jsonPath: path.join(reportDir, "report.json"),
    textPath: path.join(reportDir, "report.txt"),
    htmlPath: path.join(reportDir, "report.html"),
  };
}

/** Which recorded pairs are new (added) since the baseline, and which are stale (gone). */
export function ratchetChanges(current, recorded) {
  const currentSet = new Set(current);
  const recordedSet = new Set(recorded);
  return {
    added: current.filter((identity) => !recordedSet.has(identity)),
    gone: recorded.filter((identity) => !currentSet.has(identity)),
  };
}

export function writeKnown(pairs, selfPath = fileURLToPath(import.meta.url)) {
  const source = fs.readFileSync(selfPath, "utf8");
  const body = pairs.map((entry) => `  ${JSON.stringify(entry)},\n`).join("");
  const next = source.replace(
    /(\/\/ --- BEGIN KNOWN CROSS-PACKAGE DUPLICATE PAIRS[^\n]*\nconst KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS = \[)[\s\S]*?(\];\n\/\/ --- END KNOWN CROSS-PACKAGE DUPLICATE PAIRS ---)/,
    (_match, head, tail) => `${head}\n${body}${tail}`,
  );
  if (next === source) {
    throw new Error(
      "Could not locate the generated block in check-cross-package-duplicates.mjs",
    );
  }
  fs.writeFileSync(selfPath, next);
}

export function main(argv = process.argv.slice(2)) {
  const list = argv.includes("--list");
  const update = argv.includes("--update");
  const scope = resolveScopePaths(
    argv.filter((arg) => arg !== "--list" && arg !== "--update"),
  );

  const packages = packageRoots();
  const targets = scope.length > 0 ? scope : defaultTargets(packages, ROOT);
  const jsPairs = crossPackagePairs(runJsinspect(targets, ROOT), packages);
  const cssPairs = crossPackagePairsFromClones(runJscpd(targets, ROOT), packages, ROOT);
  const pairs = mergePairs(jsPairs, cssPairs);
  const current = [...pairs.keys()].sort();
  const known = KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS.filter((id) => pairWithinScope(scope, id));
  const report = writeReport(pairs, KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS);
  console.error(`Report: ${report.htmlPath} (${report.jsonPath})`);

  if (list) {
    console.log(`${current.length} duplicate pair(s):\n`);
    for (const id of current) {
      const tag = KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS.includes(id) ? "GATE" : "new ";
      console.log(`${tag}  ${id}`);
      for (const instance of pairs.get(id) ?? []) console.log(`        ${describeMatch(instance)}`);
    }
    return;
  }

  const { added, gone } = ratchetChanges(current, known);

  if (update) {
    if (added.length > 0) {
      console.error(
        `\u2716 --update refuses to record ${added.length} new duplicate pair(s). ` +
          "The ratchet only releases downward; fix the duplication instead:",
      );
      for (const id of added) console.error(`  + ${id}`);
      process.exitCode = 1;
      return;
    }
    writeKnown(
      [
        ...KNOWN_CROSS_PACKAGE_DUPLICATE_PAIRS.filter((id) => !pairWithinScope(scope, id)),
        ...current,
      ].sort(),
    );
    console.log(
      gone.length > 0 ?
        `\u2714 recorded ${current.length} duplicate pair(s) \u2014 ${gone.length} fewer than before.`
      : `\u2714 recorded ${current.length} duplicate pair(s) \u2014 unchanged.`,
    );
    return;
  }

  let failed = false;
  if (added.length > 0) {
    failed = true;
    console.error(`\u2716 ${added.length} new duplicate pair(s):\n`);
    for (const id of added) {
      console.error(`  + ${id}`);
      for (const instance of pairs.get(id) ?? []) console.error(`      ${describeMatch(instance)}`);
    }
    console.error(
      "\n  Extract the shared logic into a common package, or restructure so the copy" +
        " is not needed. This list is down-only: --update will not record a new pair.",
    );
  }
  if (gone.length > 0) {
    failed = true;
    console.error(
      `\n\u2716 ${gone.length} recorded pair(s) no longer match. ` +
        "Re-record so they cannot come back unnoticed:\n\n" +
        "      node scripts/check-cross-package-duplicates.mjs --update\n",
    );
    for (const id of gone) console.error(`  - ${id}`);
  }
  if (failed) {
    process.exitCode = 1;
    return;
  }
  console.log(
    `\u2713 no new duplicates (${current.length} known).`,
  );
}

const invokedPath = process.argv[1] ? fs.realpathSync(process.argv[1]) : "";
if (fs.realpathSync(fileURLToPath(import.meta.url)) === invokedPath) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
