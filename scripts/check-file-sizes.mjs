/**
 * check-file-sizes.mjs — a down-only ratchet on which tracked files exceed a
 * line-count ceiling. Same shape as
 * packages/maximal-core/scripts/check-dupes.ts's duplicate-pair ratchet: hold
 * a SET of known violations, fail only when a NEW one appears or a known one
 * silently disappears unrecorded, and let `--update` re-record the set after
 * a deliberate split.
 *
 *   node scripts/check-file-sizes.mjs                 # gate: fail on new/stale entries
 *   node scripts/check-file-sizes.mjs --list          # inventory: every file over the ceiling
 *   node scripts/check-file-sizes.mjs --update        # re-record after splitting a file
 *   node scripts/check-file-sizes.mjs <paths...>      # ripgrep-style: scope to specific paths
 *
 * Manual diagnostic, like mutation testing — not wired into check or test.
 *
 * A single ceiling, not per-path warn/error tiers: check-dupes.ts's header
 * explains why a percentage or multi-tier scheme doesn't hold up under normal
 * editing — an unrelated one-line change can flip a tier, and a scheme loose
 * enough to be green today is loose enough to swallow the thing it exists to
 * catch. This uses the same one-bit membership test that tool settled on:
 * over the ceiling, or not, tracked as a set of paths so an unrelated edit
 * elsewhere cannot perturb an entry.
 *
 * Unlike ESLint's `max-lines` (800, service packages, TypeScript only), this
 * covers every tracked file repo-wide and can be aimed at an arbitrary path
 * ad hoc, so it is a companion diagnostic, not a replacement for that gate.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const LINE_LIMIT = 800;
const EXCLUDED_NAMES = new Set(["pnpm-lock.yaml"]);
const EXCLUDED_EXTENSIONS = new Set([
  ".png", ".jpg", ".jpeg", ".gif", ".webp", ".ico", ".svg",
  ".woff", ".woff2", ".ttf", ".eot", ".map", ".lock",
  ".gz", ".zip", ".bin", ".wasm",
]);

// --- BEGIN KNOWN OVERSIZED FILES — generated by `node scripts/check-file-sizes.mjs --update` ---
