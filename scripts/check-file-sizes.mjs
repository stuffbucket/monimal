function gitFiles(scope, root = ROOT) {
  const arguments_ = ["ls-files", "--cached", "--others", "--exclude-standard", "-z"];
  if (scope.length > 0) arguments_.push("--", ...scope);
  const output = execFileSync("git", arguments_, { cwd: root, encoding: "utf8" });
  return output.length === 0 ? [] : output.split("\0").filter(Boolean);
}

function isScannable(relativePath) {
  if (EXCLUDED_NAMES.has(path.basename(relativePath))) return false;
  return !EXCLUDED_EXTENSIONS.has(path.extname(relativePath));
}

export function countLines(filePath) {
  const contents = fs.readFileSync(filePath, "utf8");
  if (contents.length === 0) return 0;
  const lines = contents.split("\n").length;
  return contents.endsWith("\n") ? lines - 1 : lines;
}

/** Ripgrep-style: files/dirs given on the command line, resolved to repo-relative POSIX paths. */
export function resolveScopePaths(rawPaths, cwd = process.cwd(), root = ROOT) {
  return rawPaths.map((raw) => {
    const relative = path.relative(root, path.resolve(cwd, raw));
    if (relative.startsWith("..") || path.isAbsolute(relative)) {
      throw new Error(`Path is outside the repository: ${raw}`);
    }
    return relative.split(path.sep).join("/");
  });
}

export function withinScope(scope, relativePath) {
  if (scope.length === 0) return true;
  return scope.some(
    (entry) => relativePath === entry || relativePath.startsWith(`${entry}/`),
  );
}

export function oversizedFiles(scope = [], root = ROOT, limit = LINE_LIMIT) {
  const files = gitFiles(scope, root).filter(isScannable).sort();
  const oversized = [];
  for (const relativePath of files) {
    const filePath = path.join(root, relativePath);
    const stat = fs.lstatSync(filePath, { throwIfNoEntry: false });
    if (!stat?.isFile()) continue;
    const lines = countLines(filePath);
    if (lines > limit) oversized.push({ path: relativePath, lines });
  }
  return oversized;
}

/** Which recorded paths are new (added) since the baseline, and which are stale (gone). */
export function ratchetChanges(current, recorded) {
  const currentSet = new Set(current);
  const recordedSet = new Set(recorded);
  return {
    added: current.filter((identity) => !recordedSet.has(identity)),
    gone: recorded.filter((identity) => !currentSet.has(identity)),
  };
}

export function writeKnown(paths, selfPath = fileURLToPath(import.meta.url)) {
  const source = fs.readFileSync(selfPath, "utf8");
  const body = paths.map((entry) => `  ${JSON.stringify(entry)},\n`).join("");
  const next = source.replace(
    /(\/\/ --- BEGIN KNOWN OVERSIZED FILES[^\n]*\nconst KNOWN_OVERSIZED_FILES = \[)[\s\S]*?(\];\n\/\/ --- END KNOWN OVERSIZED FILES ---)/,
    (_match, head, tail) => `${head}\n${body}${tail}`,
  );
  if (next === source) {
    throw new Error("Could not locate the generated block in check-file-sizes.mjs");
  }
  fs.writeFileSync(selfPath, next);
}

export function main(argv = process.argv.slice(2)) {
  const list = argv.includes("--list");
  const update = argv.includes("--update");
  const scope = resolveScopePaths(
    argv.filter((arg) => arg !== "--list" && arg !== "--update"),
  );

  const oversized = oversizedFiles(scope);
  const current = oversized.map((entry) => entry.path).sort();
  const known = KNOWN_OVERSIZED_FILES.filter((file) => withinScope(scope, file));

  if (list) {
    console.log(`${oversized.length} file(s) over ${LINE_LIMIT} lines:\n`);
    for (const entry of oversized) {
      const tag = known.includes(entry.path) ? "GATE" : "new ";
      console.log(`${tag}  ${String(entry.lines).padStart(6)}  ${entry.path}`);
    }
    return;
  }

  const { added, gone } = ratchetChanges(current, known);

  if (update) {
    if (added.length > 0) {
      console.error(
        `\u2716 --update refuses to record ${added.length} new oversized file(s). ` +
          "The ratchet only releases downward; split the file instead:",
      );
      for (const file of added) console.error(`  + ${file}`);
      process.exitCode = 1;
      return;
    }
    const outside = KNOWN_OVERSIZED_FILES.filter((file) => !withinScope(scope, file));
    writeKnown([...outside, ...current].sort());
    console.log(
      gone.length > 0 ?
        `\u2714 recorded ${current.length} oversized file(s) in scope \u2014 ${gone.length} fewer than before.`
      : `\u2714 recorded ${current.length} oversized file(s) in scope \u2014 unchanged.`,
    );
    return;
  }

  let failed = false;
  if (added.length > 0) {
    failed = true;
    console.error(`\u2716 ${added.length} newly oversized file(s) (over ${LINE_LIMIT} lines):\n`);
    for (const file of added) {
      const entry = oversized.find((candidate) => candidate.path === file);
      console.error(`  + ${file}  (${entry?.lines} lines)`);
    }
    console.error(
      "\n  Split the file. This list is down-only: --update will not record a new one.",
    );
  }
  if (gone.length > 0) {
    failed = true;
    console.error(
      `\n\u2716 ${gone.length} recorded oversized file(s) no longer exist or shrank. ` +
        "Re-record so they cannot grow back unnoticed:\n\n" +
        "      node scripts/check-file-sizes.mjs --update\n",
    );
    for (const file of gone) console.error(`  - ${file}`);
  }
  if (failed) {
    process.exitCode = 1;
    return;
  }
  console.log(
    `\u2713 no new oversized files (${current.length} known, ceiling ${LINE_LIMIT} lines).`,
  );
}

const invokedPath = process.argv[1] ? fs.realpathSync(process.argv[1]) : "";
if (fs.realpathSync(fileURLToPath(import.meta.url)) === invokedPath) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
